/// A manifest: CC0, credited to the generator, every listed asset generated by it.
fn manifest(id: &str, name: &str, version: &str, look: &str, assets: &[&str]) -> String {
    let mut s = format!(
        "# A stress pack (crates/ca72-panel/packs/stress.rs): made by code to push the format.\n\
         format = 1\nid = \"{id}\"\nname = \"{name}\"\nversion = \"{version}\"\nplugin = \"ca-72\"\n\
         summary = \"A stress pack, made by code for the CA-72's tests.\"\n\
         license = \"CC0-1.0\"\nlicense_files = [\"LICENSE.txt\"]\n\n\
         [[creators]]\nname = \"Idle Foundry Ltd.\"\nrole = \"the stress packs' generator\"\n"
    );
    for a in assets {
        let _ = write!(
            s,
            "\n[[assets]]\npath = \"{a}\"\norigin = \"original\"\nauthor = \"Idle Foundry Ltd.\"\n\
             note = \"Made by crates/ca72-panel/packs/stress.rs.\"\n"
        );
    }
    let _ = write!(s, "\n[look]\n{look}");
    s
}

fn file(path: &str, bytes: impl Into<Vec<u8>>) -> File {
    (path.to_owned(), bytes.into())
}

/// A small deterministic generator of numbers (the same packs every time).
pub struct Rng(u64);

impl Rng {
    pub fn new(seed: u64) -> Self {
        Rng(seed.max(1))
    }
    pub fn next(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }
    pub fn below(&mut self, n: u64) -> u64 {
        self.next() % n.max(1)
    }
    pub fn unit(&mut self) -> f64 {
        (self.next() >> 11) as f64 / (1u64 << 53) as f64
    }
}

// ---- EDGE

/// The panel's controls, by kind.
fn panel_params(pred: impl Fn(&Kind) -> bool) -> Vec<&'static str> {
    CONTROLS
        .iter()
        .filter(|c| c.place == Place::Panel && pred(&c.kind))
        .map(|c| c.param)
        .collect()
}

/// EDGE's layout: every control moved and at its limits, click areas touching, fixtures moved,
/// the print at its counts.
pub fn edge_layout() -> String {
    let mut s = String::from(
        "# EDGE: the layout at its limits (a stress pack, made by code).\nformat = 1\ncontrols = 1\n\n",
    );
    // Fixtures: POWER in the bottom left corner, the lamps beside it, QUALITY's opening in the
    // middle, the plate in the bottom right corner, PHONES at the largest radius, 32 screws.
    s.push_str("[fixtures]\npower = [26, 731]\nlamp = [100, 770]\noverload = [170, 761]\n");
    s.push_str("ultra = [1554, 560]\nplate = [2847, 713]\nphones = [2700, 640, 60]\nscrews = [");
    for k in 0..32 {
        let _ = write!(
            s,
            "{}[{}, -100, 7]",
            if k > 0 { ", " } else { "" },
            20 + 70 * k
        );
    }
    s.push_str("]\n\n");

    let control = |s: &mut String, param: &str, x: f64, y: f64, extra: &str| {
        let _ = write!(
            s,
            "[[control]]\nparam = \"{param}\"\nat = [{x}, {y}]\n{extra}\n"
        );
    };
    // The selectors in the wooden strip, at its top edge, right-aligned and touching.
    let selectors = panel_params(|k| matches!(k, Kind::Selector(_)));
    for (i, p) in selectors.iter().enumerate() {
        control(&mut s, p, 3048.0 - 120.0 * i as f64, -70.0, "");
    }
    // Every knob large, in one row along the face's top, touching each other and the left edge.
    let knobs = panel_params(|k| matches!(k, Kind::Knob { .. }));
    let knob = hit_bounds(&Kind::Knob {
        dial: ca72_panel::controls::Dial::Ten,
        big: true,
    });
    let (kw, kh) = (knob[2] - knob[0], knob[3] - knob[1]);
    for (i, p) in knobs.iter().enumerate() {
        control(&mut s, p, kw / 2.0 + kw * i as f64, kh / 2.0, "big = true");
    }
    // The rockers under them, touching, at sizes from the least to the most, every colour and
    // every "on" end.
    let rockers = panel_params(|k| matches!(k, Kind::Rocker { .. }));
    let sizes = [
        (16.0, 16.0),
        (240.0, 48.0),
        (48.0, 240.0),
        (108.0, 50.0),
        (16.0, 240.0),
        (240.0, 16.0),
        (60.0, 120.0),
        (120.0, 60.0),
        (200.0, 200.0),
        (16.0, 16.0),
        (110.0, 48.0),
        (55.0, 111.0),
        (44.0, 114.0),
        (240.0, 240.0),
    ];
    let colours = ["blue", "red", "black", "ivory"];
    let ends = ["right", "top", "bottom"];
    let top = kh;
    let mut x = 0.0;
    let mut tallest: f64 = 0.0;
    for (i, p) in rockers.iter().enumerate() {
        let (w, h) = sizes[i % sizes.len()];
        let (bw, bh) = (w + 8.0, h + 8.0);
        control(
            &mut s,
            p,
            x + bw / 2.0,
            top + bh / 2.0,
            &format!(
                "size = [{w}, {h}]\ncolour = \"{}\"\non = \"{}\"",
                colours[i % 4],
                ends[i % 3]
            ),
        );
        x += bw;
        tallest = tallest.max(bh);
    }
    // QUALITY's toggle on its side at its largest, under the tallest rocker, at the left edge.
    let (tw, th) = (240.0, 60.0);
    control(
        &mut s,
        "quality",
        (tw + 8.0) / 2.0,
        top + tallest + (th + 8.0) / 2.0,
        &format!("size = [{tw}, {th}]\nacross = true"),
    );

    // 300 rules: a grid over the lower face, widths from 0.5 to 20.
    let mut rng = Rng::new(7);
    for k in 0..300 {
        let width = if k == 0 {
            0.5
        } else if k == 1 {
            20.0
        } else {
            0.5 + rng.unit() * 6.0
        };
        let (from, to) = if k % 2 == 0 {
            let y = 480.0 + (k / 2) as f64 * 1.4;
            ([300.0 + (k % 7) as f64 * 10.0, y], [3000.0, y])
        } else {
            let x = 300.0 + (k / 2) as f64 * 18.0;
            ([x, 480.0], [x, 700.0])
        };
        let _ = write!(
            s,
            "[[line]]\nfrom = [{:.1}, {:.1}]\nto = [{:.1}, {:.1}]\nwidth = {width:.2}\n\n",
            from[0], from[1], to[0], to[1]
        );
    }
    // 16 titles along the foot.
    for k in 0..16 {
        let x0 = 300.0 + 170.0 * k as f64;
        let _ = write!(
            s,
            "[[title]]\ntext = \"TITLE {k:02}\"\nspan = [{x0}, {}]\nbaseline = 792\n\n",
            x0 + 160.0
        );
    }
    // 300 legends: the longest allowed, the smallest and largest sizes, moved in the large
    // lettering, some at the panel's very edges.
    for k in 0..300 {
        let text = match k {
            0 => "W".repeat(48),
            1 => "THE LONGEST LEGEND A LAYOUT MAY PRINT, 48 CHARS".to_owned(),
            _ => format!("L{k:03}"),
        };
        let (x, y) = match k {
            0 => (1554.0, 470.0),
            1 => (1554.0, 440.0),
            2 => (0.0, 300.0),
            3 => (3108.0, 300.0),
            4 => (1554.0, -130.0),
            5 => (1554.0, 795.0),
            _ => (
                320.0 + ((k - 6) % 28) as f64 * 96.0,
                500.0 + ((k - 6) / 28) as f64 * 19.0,
            ),
        };
        let size = match k % 50 {
            7 => "\nsize = 6",
            8 => "\nsize = 80",
            _ => "",
        };
        let large = if k % 3 == 0 {
            format!("\nlarge = [{}, {}]", x + 4.0, y - 4.0)
        } else {
            String::new()
        };
        let _ = write!(
            s,
            "[[text]]\ntext = \"{text}\"\nat = [{x}, {y}]{size}{large}\n\n"
        );
    }
    s
}

