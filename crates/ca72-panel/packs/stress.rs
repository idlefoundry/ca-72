//! The stress packs (decisions.md R-SKIN-PACKS): packs made by code, each pushing one part of the
//! format to its limits, so that what breaks is found before anyone's pack finds it. Shared by
//! `examples/stress_packs.rs`, which writes them out to be installed and looked at, and
//! `tests/stress.rs`, which checks each one's outcome.
//!
//! - EDGE: the layout at its limits (every control moved, click areas touching, sizes at their
//!   bounds, fixtures moved, 300 rules, 300 legends, 16 titles).
//! - HEAVY: a drawing at SVG's caps and pictures at the pack's pixel cap (cost: time and memory).
//! - EVERY PICTURE: every one of the realistic look's 27 pictures replaced by a drawing, some at
//!   other proportions, some see-through.
//! - MINIMAL: the smallest packs (a manifest alone, a layout with no print, realistic with no
//!   pictures).
//! - LIFECYCLE: one pack in many forms (versions, folder and pack file, signed and not, broken).
//! - BABEL: lettering (a wide typeface, other scripts) — with fonts, when there are some.
//!
//! What they generate is CC0 (each manifest says so); this code is the plug-in's, GPL.

