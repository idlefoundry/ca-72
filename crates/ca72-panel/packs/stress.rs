// ---- HEAVY

/// A picture `w` by `h`: smooth bands of colour (it compresses, as a PNG, to a small file).
fn png_picture(w: u32, h: u32, seed: u64) -> Vec<u8> {
    let mut p = Pixmap::new(w, h).expect("a picture");
    let mut rng = Rng::new(seed);
    let (r0, g0, b0) = (
        rng.below(200) as u8,
        rng.below(200) as u8,
        rng.below(200) as u8,
    );
    for (i, px) in p.pixels_mut().iter_mut().enumerate() {
        let (x, y) = (i as u32 % w, i as u32 / w);
        let v = ((x / 64 + y / 64) % 4) as u8 * 12;
        *px = Color::from_rgba8(r0.wrapping_add(v), g0, b0.wrapping_add(v / 2), 255)
            .premultiply()
            .to_color_u8();
    }
    p.encode_png().expect("encoded")
}

/// HEAVY's drawing: each of SVG's limits approached (elements counted as drawn, path segments,
/// filter primitives and the largest blur, a pattern's tiles, an embedded picture).
pub fn heavy_drawing() -> String {
    let mut s = String::from(
        "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 3108 925' width='3108' height='925'>\
         <title>HEAVY: a drawing at SVG's limits (a stress pack, made by code)</title><defs>",
    );
    // A tile of 40 circles, used 390 times: 15,600 elements drawn, about 78,000 segments.
    s.push_str("<g id='tile'>");
    for k in 0..40 {
        let _ = write!(
            s,
            "<circle cx='{}' cy='{}' r='2' fill='#{:02x}{:02x}80' fill-opacity='0.5'/>",
            (k % 8) * 5,
            (k / 8) * 5,
            40 + k * 4,
            200 - k * 3
        );
    }
    s.push_str("</g>");
    // A pattern of 25-unit tiles over the face: about 3,950 tiles.
    s.push_str(
        "<pattern id='grid' width='25' height='25' patternUnits='userSpaceOnUse'>\
         <rect width='12' height='12' fill='#ffffff' fill-opacity='0.05'/></pattern>",
    );
    // Six filters of five primitives each, used once each: 30 primitives, the largest blur 64.
    for f in 0..6 {
        let _ = write!(
            s,
            "<filter id='f{f}' x='-0.2' y='-0.2' width='1.4' height='1.4'>\
             <feGaussianBlur stdDeviation='{}' result='a'/><feOffset dx='3' dy='3' result='b'/>\
             <feFlood flood-color='#000' flood-opacity='0.3' result='c'/>\
             <feComposite in='c' in2='b' operator='in' result='d'/>\
             <feMerge><feMergeNode in='d'/><feMergeNode in='SourceGraphic'/></feMerge></filter>",
            if f == 0 { 64 } else { 4 + f * 8 }
        );
    }
    s.push_str("</defs>");
    s.push_str("<rect x='0' y='130' width='3108' height='795' fill='url(#grid)'/>");
    for k in 0..390 {
        let _ = write!(
            s,
            "<use href='#tile' x='{}' y='{}'/>",
            20 + (k % 78) * 39,
            150 + (k / 78) * 150
        );
    }
    // 340 paths of 300 segments each, 102,000 segments in all (with the circles' some 94,000, a
    // little under the limit of 200,000): each a level walk, short steps, so that what they cost
    // to draw stays under the drawing's limit too.
    let mut rng = Rng::new(11);
    for k in 0..340 {
        let (x0, y0) = (rng.below(2800), 140 + rng.below(780));
        let mut d = format!("M{x0} {y0}");
        for i in 0..300 {
            let _ = write!(d, " h{}", if i % 2 == 0 { 1 } else { -1 });
        }
        let _ = write!(
            s,
            "<path d='{d}' fill='none' stroke='#{:06x}' stroke-opacity='0.3' stroke-width='1'/>",
            (k * 2654435761u64 as usize) & 0xffffff
        );
    }
    for f in 0..6 {
        let _ = write!(
            s,
            "<rect x='{}' y='200' width='300' height='200' rx='20' fill='#335' filter='url(#f{f})'/>",
            100 + f * 480
        );
    }
    // An embedded picture, 1024 by 512.
    let png = png_picture(1024, 512, 3);
    let _ = write!(
        s,
        "<image x='2000' y='600' width='1024' height='512' href='data:image/png;base64,{}'/>",
        base64(&png)
    );
    s.push_str("</svg>");
    s
}

fn base64(bytes: &[u8]) -> String {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len() * 4 / 3 + 4);
    for chunk in bytes.chunks(3) {
        let b = [
            chunk[0],
            *chunk.get(1).unwrap_or(&0),
            *chunk.get(2).unwrap_or(&0),
        ];
        let n = u32::from(b[0]) << 16 | u32::from(b[1]) << 8 | u32::from(b[2]);
        for i in 0..4 {
            if i <= chunk.len() {
                out.push(T[(n >> (18 - 6 * i) & 63) as usize] as char);
            } else {
                out.push('=');
            }
        }
    }
    out
}

/// HEAVY's pictures: every slot, the walnut and the face at the largest side allowed, the rest
/// to just under the pack's pixel cap.
pub fn heavy_pictures() -> Vec<(&'static str, u32, u32)> {
    let cap: u64 = skin_pack::Limits::default().picture_pixels;
    let mut out = vec![("walnut", 2048, 2048), ("face", 2048, 2048)];
    // (Room left for the drawing's embedded picture, 1024 by 512: it counts with them.)
    let used = 2 * 2048u64 * 2048 + 1024 * 512;
    let rest = SLOTS.len() as u64 - 2;
    // The others share what is left, each square, a little under it.
    let each = ((cap - used) / rest) as f64;
    let side = (each.sqrt() * 0.99) as u32;
    for (slot, _) in SLOTS.iter().skip(2) {
        out.push((slot, side, side));
    }
    out
}

