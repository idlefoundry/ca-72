// ---- LIFECYCLE

/// The starter as `org.example.stress-lifecycle` at `version`.
fn lifecycle_files(version: &str) -> Vec<File> {
    let starter = Path::new(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../docs/skin-packs/starter"
    ));
    let mut out = Vec::new();
    for f in [
        "skin.toml",
        "layout.toml",
        "LICENSE.txt",
        "art/panel.svg",
        "README.md",
    ] {
        let mut bytes = std::fs::read(starter.join(f)).expect("the starter");
        if f == "skin.toml" {
            bytes = String::from_utf8(bytes)
                .expect("text")
                .replace("org.example.ca72-starter", "org.example.stress-lifecycle")
                .replace(
                    "name = \"STARTER\"",
                    &format!("name = \"LIFECYCLE {version}\""),
                )
                .replace("version = \"1.0.0\"", &format!("version = \"{version}\""))
                .into_bytes();
        }
        out.push(file(f, bytes));
    }
    out
}

fn as_files(files: &[File]) -> skin_pack::Files {
    let mut r = skin_pack::Report::default();
    skin_pack::Files::from_memory(
        files.iter().map(|(p, b)| (p.as_str(), b.as_slice())),
        &skin_pack::Limits::default(),
        &mut r,
    )
}

/// `files` signed with the stress key, as a pack file.
fn signed_pack_file(files: &[File], version: &str) -> Vec<u8> {
    let (secret, _) = test_key();
    let key = signature::signing_key(&secret).expect("a key");
    let set = as_files(files);
    let sig = signature::sign(
        &set,
        ("org.example.stress-lifecycle", version),
        ("stress-test", &key),
        Publisher::Marketplace,
        "2026-10-16",
    );
    let mut with = files.to_vec();
    with.push(file(signature::SIGNATURE, sig));
    skin_pack::archive::write(&as_files(&with)).expect("a pack file")
}

/// One pack in many forms, to be installed together: of these, the signed 1.1.0 is the one used
/// (signed before unsigned, then the newest); the broken and the changed ones are refused.
pub fn lifecycle() -> Vec<Pack> {
    let v1 = lifecycle_files("1.0.0");
    let v11 = lifecycle_files("1.1.0");
    let v9 = lifecycle_files("9.0.0");
    let signed = signed_pack_file(&v11, "1.1.0");
    // A pack file cut short.
    let broken = signed[..signed.len() / 2].to_vec();
    // The signed pack, a legend changed after it was signed.
    let mut changed: Vec<File> = {
        let mut r = skin_pack::Report::default();
        skin_pack::archive::read(&signed, &skin_pack::Limits::default(), &mut r)
            .iter()
            .map(|(p, b)| file(p, b))
            .collect()
    };
    for (p, b) in &mut changed {
        if p == "layout.toml" {
            *b = String::from_utf8(b.clone())
                .expect("text")
                .replacen("\"TUNE\"", "\"TUNED\"", 1)
                .into_bytes();
        }
    }
    let changed = skin_pack::archive::write(&as_files(&changed)).expect("a pack file");
    vec![
        Pack {
            name: "stress-lifecycle-1.0.0-ü".into(),
            form: Form::Folder(v1),
            expect: Expect::Loads {
                reviews: &["declaration.missing"],
            },
            about: "Version 1.0.0, unsigned, in a folder whose name is not ASCII.",
        },
        Pack {
            name: "stress-lifecycle-1.1.0.ifskin".into(),
            form: Form::PackFile(signed),
            expect: Expect::Loads {
                reviews: &["declaration.missing"],
            },
            about: "Version 1.1.0, signed with the stress key: the one used.",
        },
        Pack {
            name: "stress-lifecycle-9.0.0".into(),
            form: Form::Folder(v9),
            expect: Expect::Loads {
                reviews: &["declaration.missing"],
            },
            about: "Version 9.0.0, unsigned: never used while the signed one is installed.",
        },
        Pack {
            name: "stress-lifecycle-broken.ifskin".into(),
            form: Form::PackFile(broken),
            expect: Expect::Refused {
                codes: &["archive.format"],
            },
            about: "The signed pack file cut in half.",
        },
        Pack {
            name: "stress-lifecycle-changed.ifskin".into(),
            form: Form::PackFile(changed),
            expect: Expect::Refused {
                codes: &["signature.invalid"],
            },
            about: "The signed pack, a legend changed after it was signed.",
        },
    ]
}

