/// A drawn stand-in for a slot's picture: its shape suits the part, some at other proportions,
/// some see-through.
fn picture_svg(slot: &str, k: usize) -> String {
    let hue = (k * 37) % 360;
    let (w, h) = match slot {
        "hamster-run" => (1840, 120),
        "plate" => (1044, 328),
        "walnut" => (1400, 788),
        "power" => (112, 320),
        "rocker-blue" | "rocker-orange" => (512, 194),
        "toggle-up" | "toggle-mid" | "toggle-down" => (180, 291),
        // At other proportions than the built-in pictures: drawn so, and noted.
        "knob-big" => (512, 400),
        "jack" => (300, 256),
        _ => (300, 300),
    };
    let opacity = if k.is_multiple_of(4) { 0.5 } else { 1.0 };
    let mut s = format!(
        "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {w} {h}' width='{w}' height='{h}'>\
         <title>{slot}: a stand-in (a stress pack, made by code)</title>"
    );
    match slot {
        "hamster-run" => {
            for f in 0..8 {
                let x = f * 230 + 115;
                let _ = write!(
                    s,
                    "<ellipse cx='{x}' cy='{}' rx='70' ry='40' fill='hsl({hue},60%,60%)'/>\
                     <circle cx='{}' cy='50' r='12' fill='#222'/>",
                    60 + (f % 2) * 6,
                    x + 50
                );
            }
        }
        "walnut" | "face" | "plate" => {
            let _ = write!(
                s,
                "<rect width='{w}' height='{h}' fill='hsl({hue},40%,30%)'/>\
                 <rect x='{}' y='{}' width='{}' height='{}' fill='none' stroke='#fff' \
                 stroke-opacity='0.2' stroke-width='8'/>",
                w / 10,
                h / 10,
                w * 8 / 10,
                h * 8 / 10
            );
        }
        _ => {
            let (cx, cy, r) = (w / 2, h / 2, w.min(h) / 2 - 4);
            let _ = write!(
                s,
                "<circle cx='{cx}' cy='{cy}' r='{r}' fill='hsl({hue},70%,45%)' fill-opacity='{opacity}'/>\
                 <circle cx='{cx}' cy='{cy}' r='{}' fill='hsl({hue},20%,80%)'/>\
                 <rect x='{}' y='{}' width='8' height='{}' fill='#fff'/>",
                r * 58 / 100,
                cx - 4,
                cy - r,
                r / 2
            );
        }
    }
    s.push_str("</svg>");
    s
}

