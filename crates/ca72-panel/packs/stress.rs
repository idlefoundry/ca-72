/// Writes `pack` into the folder `dir` (a `Skins` folder, or any).
pub fn write(dir: &Path, pack: &Pack) -> std::path::PathBuf {
    let at = dir.join(&pack.name);
    match &pack.form {
        Form::Folder(files) => {
            for (p, b) in files {
                let path = at.join(p);
                std::fs::create_dir_all(path.parent().expect("a parent")).expect("a folder");
                std::fs::write(path, b).expect("written");
            }
        }
        Form::PackFile(bytes) => std::fs::write(&at, bytes).expect("written"),
    }
    at
}
