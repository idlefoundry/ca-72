/// A file of a pack: its path in the pack and its bytes.
pub type File = (String, Vec<u8>);

/// One stress pack, as it is installed: a folder, or a pack file.
pub enum Form {
    Folder(Vec<File>),
    PackFile(Vec<u8>),
}

/// What a stress pack should do.
#[derive(Clone, Debug)]
pub enum Expect {
    /// It loads, with these findings among its reviews (and no others but these).
    Loads { reviews: &'static [&'static str] },
    /// It is refused, with these findings among the reasons.
    Refused { codes: &'static [&'static str] },
}

pub struct Pack {
    /// Its name in the `Skins` folder (a folder's, or a pack file's with `.ifskin`).
    pub name: String,
    pub form: Form,
    pub expect: Expect,
    /// What it is for, for whoever installs it.
    pub about: &'static str,
}

/// A key for the stress packs' signatures (from fixed bytes: never one the plug-in trusts).
pub fn test_key() -> (String, TrustedKey) {
    let secret = "5a".repeat(32);
    let key = signature::signing_key(&secret).expect("a key");
    let public = signature::public_key(&signature::public_hex(&key)).expect("its public half");
    (
        secret,
        TrustedKey {
            id: "stress-test",
            public,
        },
    )
}

