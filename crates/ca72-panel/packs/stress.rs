/// The OFL fonts BABEL carries (tests/fonts, each with its licence; never built into the plug-in).
const UNBOUNDED: &[u8] = include_bytes!("../tests/fonts/unbounded/Unbounded[wght].ttf");
const UNBOUNDED_OFL: &str = include_str!("../tests/fonts/unbounded/OFL.txt");
const NOTO_ARABIC: &[u8] =
    include_bytes!("../tests/fonts/noto-sans-arabic/NotoSansArabic[wdth,wght].ttf");
const NOTO_ARABIC_OFL: &str = include_str!("../tests/fonts/noto-sans-arabic/OFL.txt");

/// A font BABEL carries: its file's name in the pack, bytes, licence text, and where it is from.
struct Font {
    name: &'static str,
    bytes: &'static [u8],
    ofl: &'static str,
    source: &'static str,
}

const WIDE: Font = Font {
    name: "Unbounded",
    bytes: UNBOUNDED,
    ofl: UNBOUNDED_OFL,
    source: "https://github.com/google/fonts/tree/main/ofl/unbounded",
};

const ARABIC: Font = Font {
    name: "NotoSansArabic",
    bytes: NOTO_ARABIC,
    ofl: NOTO_ARABIC_OFL,
    source: "https://github.com/google/fonts/tree/main/ofl/notosansarabic",
};

/// The starter's layout with some legends given in other words (`(starter's, BABEL's)`).
fn babel_layout(words: &[(&str, &str)]) -> String {
    let mut s = include_str!("../../../docs/skin-packs/starter/layout.toml").to_owned();
    for (from, to) in words {
        let from = format!("text = \"{from}\"");
        assert!(s.contains(&from), "{from}");
        s = s.replacen(&from, &format!("text = \"{to}\""), 1);
    }
    s
}

/// A BABEL pack: the starter's layout with `words`, in `font`'s typeface if one.
fn babel(
    name: &str,
    words: &[(&str, &str)],
    font: Option<&Font>,
    reviews: &'static [&'static str],
    about: &'static str,
) -> Pack {
    let mut files = vec![
        file("LICENSE.txt", CC0),
        file("layout.toml", babel_layout(words)),
    ];
    let mut look = String::from("base = \"classic\"\nlayout = \"layout.toml\"\n");
    let mut extra = String::new();
    if let Some(f) = font {
        let path = format!("fonts/{}.ttf", f.name);
        let ofl = format!("fonts/OFL-{}.txt", f.name);
        files.push(file(&path, f.bytes));
        files.push(file(&ofl, f.ofl));
        let _ = writeln!(look, "fonts = {{ regular = \"{path}\" }}");
        let _ = write!(
            extra,
            "\n[[assets]]\npath = \"{path}\"\norigin = \"third-party\"\nsource = \"{}\"\n\
             license = \"OFL-1.1\"\n\n[[notices]]\nname = \"{}\"\nlicense = \"OFL-1.1\"\nfile = \"{ofl}\"\n",
            f.source, f.name
        );
    }
    let id = format!("org.example.{name}");
    let text = manifest(&id, &name.to_uppercase(), "1.0.0", &look, &["layout.toml"]);
    // (The font's provenance and notice before `[look]`, as the manifest's tables go.)
    let text = text.replacen("\n[look]\n", &format!("{extra}\n[look]\n"), 1);
    files.push(file("skin.toml", text));
    Pack {
        name: name.into(),
        form: Form::Folder(files),
        expect: Expect::Loads { reviews },
        about,
    }
}

